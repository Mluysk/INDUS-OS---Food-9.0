INSERT INTO configuracoes (chave, valor) VALUES
    ('THEME_TITLE_SIZE', '26'),
    ('THEME_TITLE_OFFSET_X', '0'),
    ('THEME_TITLE_OFFSET_Y', '0')
ON DUPLICATE KEY UPDATE valor = VALUES(valor);

UPDATE configuracoes
SET valor = '26'
WHERE chave = 'THEME_TITLE_SIZE'
   OR chave LIKE 'USER%THEME_TITLE_SIZE';

UPDATE configuracoes
SET valor = '0'
WHERE chave IN ('THEME_TITLE_OFFSET_X', 'THEME_TITLE_OFFSET_Y')
   OR chave LIKE 'USER%THEME_TITLE_OFFSET_X'
   OR chave LIKE 'USER%THEME_TITLE_OFFSET_Y';
